#!/usr/bin/env python3
"""Offline, deterministic stdlib generator. No network, LLM, or dependencies."""
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools/openapi.json"
metadata = json.loads((ROOT / "tools/source.json").read_text())
assert hashlib.sha256(SOURCE.read_bytes()).hexdigest() == metadata["sha256"], "snapshot checksum mismatch"
spec = json.loads(SOURCE.read_text())


def name(value):
    initials = {"api": "API", "url": "URL", "id": "ID", "usd": "USD", "http": "HTTP"}
    return "".join(initials.get(v.lower(), v[:1].upper() + v[1:]) for v in re.split(r"[^a-zA-Z0-9]+", value) if v)


def go_strings(values):
    return "[]string{" + ",".join(json.dumps(v) for v in values) + "}"


header = "// Code generated by tools/generate.py from tools/openapi.json; DO NOT EDIT.\npackage desearch\n\n"
constants = []
entries = []
seen = set()
for path, methods in sorted(spec["paths"].items()):
    for method, operation in sorted(methods.items()):
        if method not in ("get", "post", "put", "patch", "delete", "head", "options", "trace"):
            continue
        ident = "Op" + name(operation["operationId"])
        assert ident not in seen, "duplicate Go operation name"
        seen.add(ident)
        params = methods.get("parameters", []) + operation.get("parameters", [])
        paths = [p["name"] for p in params if p["in"] == "path"]
        queries = [p["name"] for p in params if p["in"] == "query" and p.get("required")]
        content = {}
        for status, response in operation["responses"].items():
            if status.startswith("2"):
                content.update(response.get("content", {}))
        stream = "text/event-stream" in content
        is_json = "application/json" in content
        constants.append(f"// {ident} invokes {method.upper()} {path}.\n{ident} Operation = {json.dumps(operation['operationId'])}\n")
        entries.append(f"{ident}: {{method:{json.dumps(method.upper())},path:{json.dumps(path)},pathParams:{go_strings(paths)},requiredQuery:{go_strings(queries)},bodyRequired:{str(operation.get('requestBody',{}).get('required',False)).lower()},stream:{str(stream).lower()},jsonResponse:{str(is_json).lower()}}},\n")
operations = header + "// Operation identifies a route in the pinned OpenAPI schema.\ntype Operation string\n\nconst (\n" + "".join(constants) + ")\n\nvar operations = map[Operation]operationSpec{\n" + "".join(entries) + "}\n"

schemas = spec["components"]["schemas"]
needed = set()
uses_raw = False


def go_type(schema):
    global uses_raw
    if "$ref" in schema:
        key = schema["$ref"].split("/")[-1]
        needed.add(key)
        return name(key)
    if "anyOf" in schema:
        options = [s for s in schema["anyOf"] if s.get("type") != "null"]
        if len(options) == 1:
            return go_type(options[0])
    kind = schema.get("type")
    if kind == "array":
        return "[]" + go_type(schema["items"])
    if kind in ("string", "boolean", "integer", "number"):
        return {"string": "string", "boolean": "bool", "integer": "int64", "number": "float64"}[kind]
    uses_raw = True
    return "json.RawMessage"


needed.update(("SearchRequest", "SearchResponse"))
models = {}
while needed - models.keys():
    key = sorted(needed - models.keys())[0]
    schema = schemas[key]
    assert schema.get("type") == "object" and "properties" in schema, "unsupported named search schema"
    lines = [f"// {name(key)} mirrors the pinned OpenAPI {key} schema.\ntype {name(key)} struct {{\n"]
    for field, field_schema in sorted(schema["properties"].items()):
        kind = go_type(field_schema)
        optional = field not in schema.get("required", [])
        nullable = any(s.get("type") == "null" for s in field_schema.get("anyOf", []))
        if (optional or nullable) and not kind.startswith("[]") and kind != "json.RawMessage":
            kind = "*" + kind
        tag = field + (",omitempty" if optional else "")
        lines.append(f"{name(field)} {kind} `json:{json.dumps(tag)}`\n")
    models[key] = "".join(lines) + "}\n\n"
model_source = header + ('import "encoding/json"\n\n' if uses_raw else "") + "".join(models[k] for k in sorted(models))
for filename, output in (("operations_gen.go", operations), ("models_gen.go", model_source)):
    target = ROOT / filename
    target.write_text(output)
    subprocess.run(["gofmt", "-w", str(target)], check=True)
print(f"Generated {len(seen)} operations and {len(models)} web-search models from verified snapshot")
